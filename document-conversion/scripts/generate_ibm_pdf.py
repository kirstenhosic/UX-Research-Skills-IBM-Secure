def escape_xml(text):
    """Escape XML special chars for ReportLab Paragraph."""
    text = text.replace("&", "&amp;")
    text = text.replace("<", "&lt;")
    text = text.replace(">", "&gt;")
    return text


def format_inline(text):
    """Convert markdown inline formatting to ReportLab XML tags.

    The raw input is XML-escaped FIRST so any literal `&`, `<`, or `>` in
    body content survives without crashing ReportLab's mini-XML parser.
    Markdown tokens are then converted to tags we generate ourselves --
    those tags are not double-escaped because we control them."""
    text = escape_xml(text)
    # Bold + italic
    text = re.sub(r'\*\*\*(.+?)\*\*\*', r'<b><i>\1</i></b>', text)
    # Bold
    text = re.sub(r'\*\*(.+?)\*\*', r'<b>\1</b>', text)
    # Italic
    text = re.sub(r'\*(.+?)\*', r'<i>\1</i>', text)
    # Links -- only external URLs, skip internal anchors. The URL pattern
    # tolerates a single matched-paren pair (e.g. Wikipedia disambiguation
    # links: https://en.wikipedia.org/wiki/Foo_(disambiguation)).
    def _link_replace(m):
        label, url = m.group(1), m.group(2)
        if url.startswith("http://") or url.startswith("https://"):
            return f'<a href="{url}" color="#0f62fe">{label}</a>'
        return f'<b>{label}</b>'  # internal link: just bold the text
    text = re.sub(
        r'\[([^\]]+)\]\(([^\s()]+(?:\([^\s()]*\)[^\s()]*)*)\)',
        _link_replace,
        text,
    )
    return text


def _heading_text(line):
    """Return (level, text) if line is a markdown heading, else (0, '')."""
    m = re.match(r'^(#{1,6})\s+(.*)$', line.strip())
    if not m:
        return 0, ''
    return len(m.group(1)), m.group(2).strip()


def _strip_block_by_heading(md_text, heading_names):
    """Strip a heading whose text matches one of heading_names (case-insensitive),
    and everything beneath it up to the next heading. Also consume a single
    trailing '---' rule on the line directly after the block, so we don't
    leave an orphan ThinRule. Returns (block_lines_without_heading, cleaned_md_text).
    If no matching heading found, returns ([], md_text)."""
    lines = md_text.split("\n")
    targets = {h.lower() for h in heading_names}
    start = -1
    for i, line in enumerate(lines):
        level, text = _heading_text(line)
        if level and text.lower() in targets:
            start = i
            break
    if start == -1:
        return [], md_text

    # Find end: next heading line, exclusive
    end = len(lines)
    for j in range(start + 1, len(lines)):
        level, _ = _heading_text(lines[j])
        if level:
            end = j
            break

    block_lines = lines[start + 1:end]

    # Consume a trailing '---' rule (and any blank line right before it) that
    # was acting as a section terminator after this block.
    trim_end = end
    if trim_end < len(lines) and lines[trim_end].strip() in ("---", "***", "___"):
        trim_end += 1

    cleaned = "\n".join(lines[:start] + lines[trim_end:])
    return block_lines, cleaned


def extract_and_strip_toc(md_text):
    """Find a 'Contents' or 'Table of Contents' heading and parse the numbered
    list beneath it. Returns (toc_titles, md_text_without_toc_block)."""
    block_lines, cleaned = _strip_block_by_heading(
        md_text, ["contents", "table of contents"]
    )
    if not block_lines:
        return [], md_text

    titles = []
    for line in block_lines:
        m = re.match(r'^\s*\d+\.\s+(.+?)\s*$', line)
        if m:
            # Strip any markdown formatting markers from the title
            t = m.group(1).strip()
            t = re.sub(r'\*\*(.+?)\*\*', r'\1', t)
            t = re.sub(r'\*(.+?)\*', r'\1', t)
            titles.append(t)
    return titles, cleaned


def strip_cover_block(md_text):
    """Remove a '## Cover' block (heading + body + trailing rule) entirely."""
    _, cleaned = _strip_block_by_heading(md_text, ["cover"])
    return cleaned


def strip_h1_if_matches_cover(md_text, cover_title):
    """If the first H1 in the document matches cover_title (case-insensitive,
    trimmed), drop that line and a single immediately-following '---' rule.
    Avoids the cover title appearing twice when a cover page is rendered."""
    if not cover_title:
        return md_text
    lines = md_text.split("\n")
    target = cover_title.strip().lower()
    for i, line in enumerate(lines):
        level, text = _heading_text(line)
        if not level:
            continue
        if level == 1 and text.lower() == target:
            # Drop the H1 line. Also drop a single trailing '---' rule that
            # often follows a top-of-document title.
            drop_to = i + 1
            # Skip a single blank line if present before the rule
            j = drop_to
            while j < len(lines) and lines[j].strip() == "":
                j += 1
            if j < len(lines) and lines[j].strip() in ("---", "***", "___"):
                drop_to = j + 1
            return "\n".join(lines[:i] + lines[drop_to:])
        # Any other heading found before the title H1 means there's no
        # leading-title to strip; bail out.
        break
    return md_text


def suppress_leading_rule(story):
    """If the first non-Spacer flowable in the body story is a ThinRule, drop
    it. Stops a stray gray line from opening the body."""
    for i, item in enumerate(story):
        if isinstance(item, Spacer):
            continue
        if isinstance(item, ThinRule):
            del story[i]
        return story
    return story


def parse_table(lines):
    """Parse markdown table lines into ReportLab Table."""
    rows = []
    for i, line in enumerate(lines):
        line = line.strip().strip("|")
        if i == 1 and re.match(r'^[\s\-|:]+$', line):
            continue  # skip separator
        cells = [c.strip() for c in line.split("|")]
        rows.append(cells)

    if not rows:
        return None

    # Build table data with Paragraphs
    table_data = []
    for i, row in enumerate(rows):
        style = table_header_style if i == 0 else table_cell_style
        table_data.append([Paragraph(format_inline(c), style) for c in row])

    # Calculate column widths
    n_cols = len(table_data[0])
    col_w = CONTENT_W / n_cols

    t = Table(table_data, colWidths=[col_w] * n_cols, repeatRows=1)
    t.setStyle(TableStyle([
        ('BACKGROUND',      (0, 0), (-1, 0), GRAY_10),
        ('TEXTCOLOR',       (0, 0), (-1, 0), GRAY_100),
        ('FONTNAME',        (0, 0), (-1, 0), 'IBMPlexSans-SemiBold'),
        ('FONTSIZE',        (0, 0), (-1, -1), 8.5),
        ('TOPPADDING',      (0, 0), (-1, -1), 5),
        ('BOTTOMPADDING',   (0, 0), (-1, -1), 5),
        ('LEFTPADDING',     (0, 0), (-1, -1), 6),
        ('RIGHTPADDING',    (0, 0), (-1, -1), 6),
        ('LINEBELOW',       (0, 0), (-1, 0), 1, GRAY_100),
        ('LINEBELOW',       (0, 1), (-1, -1), 0.4, GRAY_20),
        ('VALIGN',          (0, 0), (-1, -1), 'TOP'),
        ('ROWBACKGROUNDS',  (0, 1), (-1, -1), [WHITE, HexColor("#fafafa")]),
    ]))
    return t


def parse_markdown(md_text, doc_title):
    """Parse markdown into ReportLab story (list of flowables).

    Returns just the story list. Body is rendered as continuous flow with
    inline headings; page breaks come from <!-- pagebreak --> only. Cover
    title and TOC are handled by separate preprocessing helpers."""
    lines = md_text.split("\n")
    story = []
    i = 0
    in_table = False
    table_lines = []

    while i < len(lines):
        line = lines[i]
        stripped = line.strip()

        # Page break marker (case-insensitive). Must be checked before the
        # generic comment skip, otherwise it would be silently swallowed.
        if re.match(r'^<!--\s*page\s*break\s*-->\s*$', stripped, re.IGNORECASE):
            story.append(PageBreak())
            i += 1
            continue

        # Skip HTML comments
        if stripped.startswith("<!--"):
            comment_start = i
            # Safety limit: max 50 lines for a comment block
            while i < len(lines) and i - comment_start < 50 and "-->" not in lines[i]:
                i += 1
            # Skip the closing line if found
            if i < len(lines) and "-->" in lines[i]:
                i += 1
            continue

        # Table detection
        if stripped.startswith("|") and not in_table:
            in_table = True
            table_lines = [stripped]
            i += 1
            continue
        elif in_table:
            if stripped.startswith("|"):
                table_lines.append(stripped)
                i += 1
                continue
            else:
                # End of table
                t = parse_table(table_lines)
                if t:
                    story.append(t)
                    story.append(Spacer(1, 8))
                in_table = False
                table_lines = []
                # Don't increment i, re-process this line
                continue

        # Horizontal rule
        if stripped in ("---", "***", "___"):
            # Skip the very first line (treat a leading rule as YAML
            # frontmatter delimiter rather than a body rule).
            if i > 0:
                story.append(ThinRule())
                story.append(Spacer(1, 6))
            i += 1
            continue

        # H1 -- inline only. No PageBreak, no BlueBar treatment. The cover
        # page (if rendered) handles the document title; preprocessing strips
        # a leading H1 that matches the cover title.
        if stripped.startswith("# ") and not stripped.startswith("## "):
            title = stripped[2:].strip()
            story.append(Paragraph(format_inline(title), section_title_style))
            i += 1
            continue

        # H2 -- inline only. Render verbatim so authored numbering ("1. Foo")
        # is preserved in the body. The TOC display strips numbering separately.
        if stripped.startswith("## "):
            title = stripped[3:].strip()
            story.append(Paragraph(format_inline(title), h2_style))
            i += 1
            continue

        # H3
        if stripped.startswith("### ") and not stripped.startswith("#### "):
            title = stripped[4:].strip()
            story.append(Paragraph(format_inline(title), h3_style))
            i += 1
            continue

        # H4/H5/H6 — render at H3 size (smallest heading style we have)
        if stripped.startswith("#### "):
            title = stripped.lstrip("#").strip()
            story.append(Paragraph(format_inline(title), h3_style))
            i += 1
            continue

        # Blockquote -> CalloutBox
        if stripped.startswith("> "):
            quote_lines = []
            quote_start = i
            # Safety limit: max 20 lines per quote
            while i < len(lines) and i - quote_start < 20 and lines[i].strip().startswith("> "):
                q = lines[i].strip()[2:].strip()
                # Strip italic markers from quotes
                q = re.sub(r'^\*"?|"?\*$', '', q)
                q = q.strip('"').strip()
                quote_lines.append(q)
                i += 1

            quote_text = " ".join(quote_lines)
            
            # Limit quote length to prevent ReportLab issues
            if len(quote_text) > 1000:
                quote_text = quote_text[:1000] + "..."

            # Check for attribution on next line
            attribution = None
            if i < len(lines):
                next_line = lines[i].strip()
                # Match patterns like "-- Name, ID" or "> -- Name"
                attr_match = re.match(r'^(?:>?\s*)?(?:\u2014|--|---)\s*(.+)$', next_line)
                if attr_match:
                    attribution = attr_match.group(1).strip()
                    i += 1

            try:
                story.append(Spacer(1, 8))
                story.append(KeepTogether([
                    CalloutBox(
                        escape_xml(quote_text),
                        escape_xml(attribution) if attribution else None,
                    )
                ]))
                story.append(Spacer(1, 8))
            except Exception as e:
                print(f"WARNING: Failed to create quote at line {quote_start}: {e}", file=sys.stderr)
                # Skip this quote and continue
                pass
            continue

        # Sub-bullet (indented)
        if re.match(r'^  +[-*]\s', line):
            text = re.sub(r'^\s+[-*]\s+', '', line).strip()
            story.append(Paragraph(
                f'<bullet>\u2022</bullet>{format_inline(text)}',
                sub_bullet_style
            ))
            i += 1
            continue

        # Bullet
        if stripped.startswith("- ") or stripped.startswith("* "):
            text = stripped[2:].strip()
            story.append(Paragraph(
                f'<bullet>\u2014</bullet>{format_inline(text)}',
                bullet_style
            ))
            i += 1
            continue

        # Empty line
        if not stripped:
            i += 1
            continue

        # Body text
        # Collect consecutive non-empty, non-special lines
        para_lines = []
        start_i = i
        while i < len(lines):
            # Safety check: prevent infinite loops
            if i - start_i > 100:
                print(f"WARNING: Breaking paragraph collection at line {i} (too many lines)", file=sys.stderr)
                break
            
            l = lines[i].strip()
            if not l or l.startswith("#") or l.startswith("|") or l.startswith(">") or l.startswith("- ") or l.startswith("* ") or l.startswith("<!--") or re.match(r'^  +[-*]\s', lines[i]):
                break
            para_lines.append(l)
            i += 1

        if para_lines:
            text = " ".join(para_lines)
            # Limit text length to prevent ReportLab hangs
            if len(text) > 3000:
                text = text[:3000] + "..."
            try:
                story.append(Paragraph(format_inline(text), body_style))
            except Exception as e:
                print(f"WARNING: Failed to create paragraph at line {start_i}: {e}", file=sys.stderr)
                # Skip this paragraph and continue
                pass
        else:
            # Current line is unrecognized (matched an inner-loop break condition
            # that the outer loop doesn't explicitly handle — e.g. a bare ">",
            # a "#foo" with no space, or a heading level we don't render).
            # Advance unconditionally so we never spin on the same line.
            print(f"WARNING: Skipping unrecognized line {i}: {lines[i][:80]!r}", file=sys.stderr)
            i += 1

    # Flush remaining table
    if in_table and table_lines:
        t = parse_table(table_lines)
        if t:
            story.append(t)

    return story


