def _resolve_font_dir(cli_font_dir=None):
    """Pick the first existing font directory from the resolution chain:
    1. --font-dir CLI flag
    2. ~/Documents/IBM_Plex_Sans/static
    3. <skill>/assets/fonts (relative to this script)
    4. /Library/Fonts (macOS system fonts)
    5. ~/Library/Fonts (macOS user fonts)
    6. /usr/share/fonts (Linux system fonts)
    7. ~/.local/share/fonts (Linux user fonts)
    
    For system directories, we check if IBM Plex Sans fonts exist before
    returning the directory.
    Returns the chosen path, or None if none exist."""
    candidates = []
    
    # Priority 1-3: Explicit locations (existing behavior)
    if cli_font_dir:
        candidates.append(os.path.expanduser(cli_font_dir))
    candidates.append(os.path.expanduser("~/Documents/IBM_Plex_Sans/static"))
    candidates.append(os.path.join(
        os.path.dirname(os.path.abspath(__file__)), "..", "assets", "fonts"
    ))
    
    # Check explicit candidates first
    for c in candidates:
        if c and os.path.isdir(c):
            return c
    
    # Priority 4-7: System font directories
    # Only return these if they contain IBM Plex Sans fonts
    system_candidates = [
        "/Library/Fonts",                           # macOS system
        os.path.expanduser("~/Library/Fonts"),      # macOS user
        "/usr/share/fonts",                         # Linux system
        os.path.expanduser("~/.local/share/fonts"), # Linux user
    ]
    
    for sys_dir in system_candidates:
        if os.path.isdir(sys_dir):
            # Check if IBM Plex Sans fonts exist in this directory
            # Look for at least one IBMPlexSans-*.ttf file
            try:
                for entry in os.listdir(sys_dir):
                    if entry.startswith("IBMPlexSans-") and entry.endswith(".ttf"):
                        return sys_dir
                # Also check subdirectories (fonts might be in IBM_Plex_Sans/ subfolder)
                for entry in os.listdir(sys_dir):
                    subdir = os.path.join(sys_dir, entry)
                    if os.path.isdir(subdir) and "plex" in entry.lower():
                        for subentry in os.listdir(subdir):
                            if subentry.startswith("IBMPlexSans-") and subentry.endswith(".ttf"):
                                return subdir
            except (OSError, PermissionError):
                continue
    
    return None


def _download_ibm_plex_fonts():
    """Download IBM Plex Sans fonts from GitHub to ~/Documents/IBM_Plex_Sans/static.
    Returns True if successful, False otherwise."""
    import urllib.request
    import zipfile
    import tempfile
    
    target_dir = os.path.expanduser("~/Documents/IBM_Plex_Sans/static")
    
    print("\nDownloading IBM Plex Sans fonts from GitHub...", file=sys.stderr)
    
    try:
        # IBM Plex Sans GitHub release URL
        zip_url = "https://github.com/IBM/plex/releases/download/v6.4.0/TrueType.zip"
        
        # Download to temp file
        with tempfile.NamedTemporaryFile(delete=False, suffix='.zip') as tmp_file:
            tmp_path = tmp_file.name
            print(f"Downloading from {zip_url}...", file=sys.stderr)
            urllib.request.urlretrieve(zip_url, tmp_path)
        
        # Extract IBM Plex Sans fonts
        os.makedirs(target_dir, exist_ok=True)
        
        with zipfile.ZipFile(tmp_path, 'r') as zip_ref:
            # Extract only IBM Plex Sans static fonts
            for file_info in zip_ref.filelist:
                if 'IBM-Plex-Sans/fonts/complete/ttf/' in file_info.filename and file_info.filename.endswith('.ttf'):
                    # Extract just the filename
                    filename = os.path.basename(file_info.filename)
                    if filename:  # Skip directory entries
                        target_path = os.path.join(target_dir, filename)
                        with zip_ref.open(file_info) as source, open(target_path, 'wb') as target:
                            target.write(source.read())
        
        # Clean up temp file
        os.unlink(tmp_path)
        
        # Verify fonts were extracted
        fonts = [f for f in os.listdir(target_dir) if f.startswith('IBMPlexSans-') and f.endswith('.ttf')]
        if fonts:
            print(f"✓ Successfully downloaded {len(fonts)} IBM Plex Sans fonts to {target_dir}", file=sys.stderr)
            return True
        else:
            print(f"✗ Download completed but no fonts found in {target_dir}", file=sys.stderr)
            return False
            
    except Exception as e:
        print(f"✗ Failed to download fonts: {e}", file=sys.stderr)
        return False


def _prompt_for_font_location():
    """Interactively prompt user for font location or offer to download.
    Returns font directory path or None."""
    print("\n" + "="*70, file=sys.stderr)
    print("IBM Plex Sans fonts not found in standard locations.", file=sys.stderr)
